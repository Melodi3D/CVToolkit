def snap_tool():
    '''
    Snaps objects to each other
    '''
    object_selection = cmds.ls(selection=True)

    if len(object_selection) < 2:
        raise RuntimeError("Select two objects to snap")

    cmds.matchTransform(object_selection[0], object_selection[1])

